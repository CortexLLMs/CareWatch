const AppCtx = createContext(null);

export function AppProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    try {
      const l = localStorage.getItem("carewatch_lang");
      return LANGS.includes(l) ? l : "fr";
    } catch { return "fr"; }
  });
  const [theme, setThemeState] = useState(() => {
    try {
      const t = localStorage.getItem("carewatch_theme");
      if (t === "dark" || t === "light") return t;
      return window.matchMedia("(prefers-color-scheme: dark)").matches ? "dark" : "light";
    } catch { return "light"; }
  });

  useEffect(() => {
    try { localStorage.setItem("carewatch_lang", lang); } catch {}
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  }, [lang]);

  useEffect(() => {
    try { localStorage.setItem("carewatch_theme", theme); } catch {}
    document.documentElement.dataset.theme = theme;
  }, [theme]);

  const setLang = useCallback((l) => { if (LANGS.includes(l)) setLangState(l); }, []);
  const cycleLang = useCallback(() => setLangState((p) => LANGS[(LANGS.indexOf(p) + 1) % LANGS.length]), []);
  const toggleTheme = useCallback(() => setThemeState((p) => (p === "dark" ? "light" : "dark")), []);

  const t = useCallback(
    (key, vars) => {
      let s = dict[lang][key] ?? dict.en[key] ?? key;
      if (vars) for (const k of Object.keys(vars)) s = s.split("{" + k + "}").join(vars[k]);
      return s;
    },
    [lang]
  );

  const locale = LOCALES[lang];

  return (
    <AppCtx.Provider value={{ t, lang, setLang, cycleLang, locale, theme, toggleTheme }}>
      {children}
    </AppCtx.Provider>
  );
}

export function useT() {
  return useContext(AppCtx);
}
